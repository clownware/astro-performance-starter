#!/usr/bin/env tsx
/**
 * Generated ADR index (ADR-066).
 *
 * Renders one table row per record in `docs/adr/` — number, title, status and
 * the checks that enforce it — between the `adr-index` markers in
 * `docs/adr/README.md`. Titles and statuses come from each record; enforcing
 * checks come from `checks/enforcement.config.json`. Nothing is hand-written,
 * so the index cannot drift from the log (the failure ADR-059 and ADR-061 exist
 * to prevent).
 *
 * Mirrors the `agents:build` / `agents:check` pattern: the rendering is pure
 * and unit-tested; this file is also the I/O shell.
 *
 * Usage: pnpm run adr:index   (rewrite the index)
 *        pnpm run adr:check   (exit non-zero if the index is stale; in quality:ci)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export interface AdrRecord {
  file: string;
  id: string;
  title: string;
  status: string;
}

export interface IndexCheck {
  id: string;
  adr: string;
  status: string;
  external?: string;
}

const startMarker = "<!-- adr-index:start -->";
const endMarker = "<!-- adr-index:end -->";

/** Read the number, title and canonical status word from one ADR file. */
export function parseAdr(file: string, content: string): AdrRecord {
  const id = `ADR-${file.slice(0, 3)}`;
  const rawTitle = content.match(/^title:\s*(.+)$/m)?.[1]?.trim() ?? file;
  const title = rawTitle
    .replace(/^(['"])(.*)\1$/, "$2")
    .replace(/^ADR-\d{3}:\s*/, "")
    .trim();
  const status = content.match(/## Status\s*\n+([A-Za-z]+)/)?.[1] ?? "Unknown";
  return { file, id, title, status };
}

const cell = (text: string): string => text.replace(/\|/g, "\\|");

/** Render the index block: a count line and one table row per record. */
export function renderIndex(adrs: AdrRecord[], checks: IndexCheck[]): string {
  const rows = adrs.map((adr) => {
    const enforced = checks
      .filter((c) => c.adr === adr.id)
      .map((c) => `\`${c.id}\` (${c.status}${c.external ? ", external gate" : ""})`)
      .join(", ");
    return `| [${adr.id}](${adr.file}) | ${cell(adr.title)} | ${adr.status} | ${enforced || "–"} |`;
  });
  return [
    `${adrs.length} records. Generated by \`pnpm adr:index\` from each record's title and status and from \`checks/enforcement.config.json\`; do not edit by hand.`,
    "",
    "| ADR | Title | Status | Enforced by |",
    "| --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

/** Replace the text between the index markers. Throws if either is missing. */
export function spliceIndex(readme: string, block: string): string {
  const start = readme.indexOf(startMarker);
  const end = readme.indexOf(endMarker);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`docs/adr/README.md is missing the ${startMarker} / ${endMarker} markers`);
  }
  return `${readme.slice(0, start + startMarker.length)}\n${block}\n${readme.slice(end)}`;
}

function main(): void {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
  const adrDir = join(root, "docs", "adr");
  const readmePath = join(adrDir, "README.md");
  const adrs = readdirSync(adrDir)
    .filter((f) => /^\d{3}-.*\.md$/.test(f))
    .sort()
    .map((f) => parseAdr(f, readFileSync(join(adrDir, f), "utf-8")));
  const { checks } = JSON.parse(
    readFileSync(join(root, "checks", "enforcement.config.json"), "utf-8"),
  ) as { checks: IndexCheck[] };

  const existing = readFileSync(readmePath, "utf-8");
  const generated = spliceIndex(existing, renderIndex(adrs, checks));

  if (process.argv[2] === "check") {
    if (existing !== generated) {
      console.error("❌ docs/adr/README.md index is out of date with docs/adr/ or the registry.");
      console.error("   Run `pnpm adr:index` and commit the result.");
      process.exit(1);
    }
    console.log(`✅ ADR index is in sync (${adrs.length} records).`);
    return;
  }
  writeFileSync(readmePath, generated);
  console.log(`✅ Wrote the ADR index (${adrs.length} records).`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
